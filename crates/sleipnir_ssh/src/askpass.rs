//! SSH_ASKPASS plumbing.
//!
//! `ssh` refuses to read a password from anywhere but a TTY, so when Sleipnir
//! wants to collect a passphrase or a password itself it must speak the
//! `SSH_ASKPASS` protocol: point `SSH_ASKPASS` at an executable, and `ssh`
//! runs it with the prompt as `argv[1]`, expecting the secret on stdout.
//!
//! Shipping a second compiled helper would not survive the Linux/Windows
//! installers (they only carry the main binary), so instead we generate a tiny
//! `sh` script next to the config that `exec`s the running Sleipnir binary
//! with a hidden `ssh-askpass` subcommand. That subcommand is
//! [`run_askpass_client`], and it talks to the pane that spawned `ssh` over a
//! private Unix socket.
//!
//! Wire protocol: one JSON value per `\n`-terminated line (same style as the
//! control surface). The client sends [`AskpassMessage::Request`], the server
//! answers with exactly one [`AskpassMessage::Secret`] or
//! [`AskpassMessage::Cancel`], then both sides close.

use std::io::{BufRead, BufReader, Write};
use std::path::{Path, PathBuf};
use std::time::Duration;

use serde::{Deserialize, Serialize};

/// Environment variable `ssh` reads the askpass program from.
pub const ASKPASS_ENV: &str = "SSH_ASKPASS";
/// Environment variable that makes OpenSSH >= 8.4 use askpass even with a TTY.
pub const ASKPASS_REQUIRE_ENV: &str = "SSH_ASKPASS_REQUIRE";
/// Environment variable carrying the socket the helper connects to.
pub const ASKPASS_SOCKET_ENV: &str = "SLEIPNIR_SSH_ASKPASS_SOCK";

/// Upper bound for a single protocol line. Prompts are short; this only exists
/// so a broken peer cannot make us allocate without bound.
pub const MAX_MESSAGE_BYTES: usize = 64 * 1024;

/// How long the helper waits for the app to accept a connection.
pub const CONNECT_TIMEOUT: Duration = Duration::from_secs(10);
/// How long the helper waits for the user to answer.
pub const ANSWER_TIMEOUT: Duration = Duration::from_secs(600);

/// One protocol message.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum AskpassMessage {
    /// Helper -> app: `ssh` is asking for this prompt.
    Request { prompt: String },
    /// App -> helper: the secret, to be printed on stdout.
    Secret { value: String },
    /// App -> helper: the user declined; exit non-zero.
    Cancel,
}

impl AskpassMessage {
    /// Serialize as one protocol line (with trailing newline).
    pub fn to_line(&self) -> String {
        let mut line = serde_json::to_string(self).unwrap_or_else(|_| "{}".to_string());
        line.push('\n');
        line
    }

    /// Parse one protocol line, tolerating surrounding whitespace.
    pub fn from_line(line: &str) -> Option<Self> {
        serde_json::from_str(line.trim()).ok()
    }
}

/// Directory holding per-connection askpass sockets.
pub fn socket_dir() -> PathBuf {
    sleipnir_paths::config_dir().join("ssh-askpass")
}

/// Path of the generated askpass script.
pub fn askpass_script_path() -> PathBuf {
    sleipnir_paths::config_dir().join("ssh").join("askpass")
}

/// A short, unique socket file name. Unix socket paths are limited to ~104
/// bytes, so this is deliberately terse.
pub fn socket_file_name() -> String {
    let hex = uuid::Uuid::new_v4().simple().to_string();
    format!("{}.sock", &hex[..16])
}

/// Write (or refresh) the askpass script so it execs `exe`.
///
/// Returns the script path. The file is only rewritten when its content would
/// change, so upgrading the app silently repoints it at the new binary.
#[cfg(unix)]
pub fn ensure_askpass_script(exe: &Path) -> anyhow::Result<PathBuf> {
    use std::os::unix::fs::PermissionsExt as _;

    let path = askpass_script_path();
    let body = format!(
        "#!/bin/sh\n# Generated by Sleipnir. Do not edit.\nexec {} ssh-askpass \"$@\"\n",
        shell_quote(exe)
    );
    if std::fs::read_to_string(&path).ok().as_deref() != Some(body.as_str()) {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(&path, body.as_bytes())?;
    }
    let mut permissions = std::fs::metadata(&path)?.permissions();
    permissions.set_mode(0o700);
    std::fs::set_permissions(&path, permissions)?;
    Ok(path)
}

/// Non-Unix platforms have no `SSH_ASKPASS`; the caller never invokes this.
#[cfg(not(unix))]
pub fn ensure_askpass_script(_exe: &Path) -> anyhow::Result<PathBuf> {
    Ok(askpass_script_path())
}

/// Single-quote a path for `sh`, keeping it on one token.
fn shell_quote(path: &Path) -> String {
    let raw = path.to_string_lossy();
    if raw
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || "/._-".contains(c))
    {
        return raw.into_owned();
    }
    let mut out = String::from("'");
    for ch in raw.chars() {
        if ch == '\'' {
            out.push_str("'\\''");
        } else {
            out.push(ch);
        }
    }
    out.push('\'');
    out
}

/// Client half: connect, ask, and return the secret (or `None` when cancelled).
#[cfg(unix)]
pub fn askpass(socket: &Path, prompt: &str) -> anyhow::Result<Option<String>> {
    use std::os::unix::net::UnixStream;

    let mut stream = UnixStream::connect(socket)?;
    stream.set_write_timeout(Some(CONNECT_TIMEOUT))?;
    stream.set_read_timeout(Some(ANSWER_TIMEOUT))?;
    stream.write_all(
        AskpassMessage::Request {
            prompt: prompt.to_string(),
        }
        .to_line()
        .as_bytes(),
    )?;
    stream.flush()?;

    let mut line = String::new();
    let mut reader = BufReader::new(stream);
    let read = reader.read_line(&mut line)?;
    if read == 0 {
        anyhow::bail!("askpass peer closed without answering");
    }
    match AskpassMessage::from_line(&line) {
        Some(AskpassMessage::Secret { value }) => Ok(Some(value)),
        Some(AskpassMessage::Cancel) | None => Ok(None),
        Some(AskpassMessage::Request { .. }) => Ok(None),
    }
}

/// Entry point for the hidden `sleipnir ssh-askpass` subcommand.
///
/// Prints the secret on stdout and exits 0, or exits 1 without printing
/// anything when the user cancels or the app is unreachable.
#[cfg(unix)]
pub fn run_askpass_client() -> i32 {
    let prompt = std::env::args()
        .nth(1)
        .unwrap_or_else(|| "Password:".to_string());
    let Some(socket) = std::env::var_os(ASKPASS_SOCKET_ENV).map(PathBuf::from) else {
        log::warn!("{ASKPASS_SOCKET_ENV} is not set; cannot ask for the password");
        return 1;
    };
    match askpass(&socket, &prompt) {
        Ok(Some(secret)) => {
            println!("{secret}");
            0
        }
        Ok(None) => 1,
        Err(err) => {
            log::warn!("ssh-askpass failed: {err:#}");
            1
        }
    }
}

/// Unreachable: Windows builds never set `SSH_ASKPASS`.
#[cfg(not(unix))]
pub fn run_askpass_client() -> i32 {
    log::warn!("ssh-askpass is only supported on unix platforms");
    2
}

#[cfg(all(test, unix))]
mod tests {
    use super::*;
    use std::os::unix::fs::PermissionsExt as _;
    use std::os::unix::net::UnixListener;

    #[test]
    fn message_round_trips_over_the_wire() {
        let request = AskpassMessage::Request {
            prompt: "user@host's password: ".into(),
        };
        let line = request.to_line();
        assert!(line.ends_with('\n'));
        assert_eq!(AskpassMessage::from_line(&line), Some(request));

        let secret = AskpassMessage::Secret {
            value: "p@ss w0rd".into(),
        };
        assert_eq!(AskpassMessage::from_line(&secret.to_line()), Some(secret));
        assert_eq!(
            AskpassMessage::from_line("{\"kind\":\"cancel\"}"),
            Some(AskpassMessage::Cancel)
        );
        assert_eq!(AskpassMessage::from_line("not json"), None);
    }

    #[test]
    fn askpass_client_prints_the_secret_it_was_given() {
        let dir = tempfile::tempdir().unwrap();
        let socket = dir.path().join(socket_file_name());
        let listener = UnixListener::bind(&socket).unwrap();
        let server = std::thread::spawn(move || {
            let (mut stream, _) = listener.accept().unwrap();
            let mut reader = BufReader::new(stream.try_clone().unwrap());
            let mut line = String::new();
            reader.read_line(&mut line).unwrap();
            let message = AskpassMessage::from_line(&line).unwrap();
            assert!(matches!(message, AskpassMessage::Request { .. }));
            stream
                .write_all(
                    AskpassMessage::Secret {
                        value: "s3cret".into(),
                    }
                    .to_line()
                    .as_bytes(),
                )
                .unwrap();
            stream.flush().unwrap();
        });

        let answer = askpass(&socket, "Password: ").unwrap();
        server.join().unwrap();
        assert_eq!(answer.as_deref(), Some("s3cret"));
    }

    #[test]
    fn askpass_client_reports_cancel_as_no_secret() {
        let dir = tempfile::tempdir().unwrap();
        let socket = dir.path().join(socket_file_name());
        let listener = UnixListener::bind(&socket).unwrap();
        let server = std::thread::spawn(move || {
            let (mut stream, _) = listener.accept().unwrap();
            stream
                .write_all(AskpassMessage::Cancel.to_line().as_bytes())
                .unwrap();
        });

        let outcome = askpass(&socket, "Password: ");
        server.join().unwrap();
        match &outcome {
            Ok(value) => assert_eq!(value, &None),
            Err(err) => panic!("askpass failed: {err:#}"),
        }
    }

    #[test]
    fn askpass_script_is_executable_and_idempotent() {
        let dir = tempfile::tempdir().unwrap();
        let exe = dir.path().join("sleipnir");
        let path = ensure_askpass_script(&exe).unwrap();
        let body = std::fs::read_to_string(&path).unwrap();
        assert!(body.starts_with("#!/bin/sh\n"), "{body}");
        assert!(body.contains("ssh-askpass \"$@\""), "{body}");
        assert!(body.contains(&exe.display().to_string()), "{body}");
        let mode = std::fs::metadata(&path).unwrap().permissions().mode();
        assert_eq!(mode & 0o777, 0o700);

        // Second call must not rewrite the file (mtime stays put).
        let modified = std::fs::metadata(&path).unwrap().modified().unwrap();
        ensure_askpass_script(&exe).unwrap();
        assert_eq!(
            std::fs::metadata(&path).unwrap().modified().unwrap(),
            modified
        );
    }

    #[test]
    fn script_quotes_paths_with_spaces() {
        assert_eq!(
            shell_quote(Path::new("/opt/My App/sleipnir")),
            "'/opt/My App/sleipnir'"
        );
        assert_eq!(
            shell_quote(Path::new("/usr/bin/sleipnir")),
            "/usr/bin/sleipnir"
        );
    }

    #[test]
    fn socket_names_are_short_and_unique() {
        let a = socket_file_name();
        let b = socket_file_name();
        assert_ne!(a, b);
        assert!(a.len() <= 24, "{a}");
        assert!(a.ends_with(".sock"));
    }
}
